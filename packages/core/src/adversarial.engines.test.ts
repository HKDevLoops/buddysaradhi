describe("ATTACK 11 — generateReport (fees CSV)", () => {
  it("ATK-11.1 [P2] the fees CSV is direction-blind: a charge and a payment print identically", async () => {
    // BR-RPT-02: the Student Ledger Report lists every row with `type`,
    // `direction`, `amount`, and `void` status. The CSV has a Type column but
    // no DIRECTION and no VOID marker, so a ₹1,000 charge and a ₹1,000
    // payment are the same line of text.
    const tenantId = await seedTenant();
    const studentId = await seedStudent(tenantId);
    await prisma.ledgerEntry.create({
      data: {
        id: randomUUID(),
        tenantId,
        studentId,
        type: "FEE_CHARGED",
        debitPaise: 100000,
        creditPaise: 0,
        balanceAfterPaise: 100000,
        description: "September fee",
        thisHash: "h1",
        occurredOn: "2026-09-01",
        createdAt: new Date("2026-09-01T10:00:00.000Z"),
      },
    });
    await prisma.ledgerEntry.create({
      data: {
        id: randomUUID(),
        tenantId,
        studentId,
        type: "PAYMENT_RECEIVED",
        debitPaise: 0,
        creditPaise: 100000,
        balanceAfterPaise: 0,
        description: "Cash",
        thisHash: "h2",
        occurredOn: "2026-09-02",
        createdAt: new Date("2026-09-02T10:00:00.000Z"),
      },
    });
    await prisma.ledgerEntry.create({
      data: {
        id: randomUUID(),
        tenantId,
        studentId,
        type: "VOID",
        debitPaise: 100000,
        creditPaise: 0,
        balanceAfterPaise: 0,
        description: "VOID: wrong entry",
        thisHash: "h3",
        occurredOn: "2026-09-03",
        createdAt: new Date("2026-09-03T10:00:00.000Z"),
      },
    });

    const csv = await generateReport(prisma, { tenantId, type: "fees" });
    const file = join(tmpDir, "fees.csv");
    writeFileSync(file, csv, "utf8");
    const onDisk = readFileSync(file, "utf8");
    // eslint-disable-next-line no-console
    console.log("[ATK-11.1] CSV bytes:\n" + onDisk);
    // eslint-disable-next-line no-console
    console.log("[ATK-11.1] first byte:", onDisk.charCodeAt(0), "(BOM would be 239,187,191)");
    // The charge and the payment are indistinguishable.
    expect(onDisk).toContain('"FEE_CHARGED","1000.00"');
    expect(onDisk).toContain('"PAYMENT_RECEIVED","1000.00"');
    // A VOID row is not marked as voided — it prints like any other line.
    expect(onDisk).toContain('"VOID","1000.00"');
    // There is no direction column and no BOM.
    expect(onDisk.split("\n")[0]).toBe("Date,Student,Type,Amount (INR)");
    expect(onDisk.charCodeAt(0)).not.toBe(0xfeff);
  });

  it("ATK-11.2 [P2] the CSV writes RUPEES, not paise — the exported file is not the data layer's unit", async () => {
    // BR-M-01: the data layer never stores a float. The export divides by
    // 100 and rounds to 2 decimals, so the file is a lossy, second
    // representation of the money with no way back to the stored paise.
    const tenantId = await seedTenant();
    const studentId = await seedStudent(tenantId);
    await prisma.ledgerEntry.create({
      data: {
        id: randomUUID(),
        tenantId,
        studentId,
        type: "PAYMENT_RECEIVED",
        debitPaise: 0,
        creditPaise: 150055,
        balanceAfterPaise: 0,
        description: "Cash",
        thisHash: "h",
        occurredOn: "2026-09-01",
        createdAt: new Date("2026-09-01T10:00:00.000Z"),
      },
    });
    const csv = await generateReport(prisma, { tenantId, type: "fees" });
    // eslint-disable-next-line no-console
    console.log("[ATK-11.2] CSV:", JSON.stringify(csv));
    // ₹1,500.55 — correct to the paisa, but the file no longer holds the
    // integer the ledger holds, and BR-M-02 says the display convention is
    // en-IN with ZERO decimals (`maximumFractionDigits: 0`).
    expect(csv).toContain('"1500.55"');
  });

  it("ATK-11.3 [P2] the fees export reads the ledger with NO bound", async () => {
    // `db.ledgerEntry.findMany({ where: { tenantId, createdAt: {...} } })` —
    // no `take`, no cursor, no chunking. A tenant with a year of history
    // materialises every row (and every joined student) into one worker
    // payload. BR-RPT-02 wants a report; it does not want an OOM.
    const tenantId = await seedTenant();
    const studentId = await seedStudent(tenantId);
    for (let i = 0; i < 5; i++) {
      await prisma.ledgerEntry.create({
        data: {
          id: randomUUID(),
          tenantId,
          studentId,
          type: "PAYMENT_RECEIVED",
          debitPaise: 0,
          creditPaise: 100,
          balanceAfterPaise: 0,
          description: `p${i}`,
          thisHash: `h${i}`,
          occurredOn: "2026-09-01",
          createdAt: new Date(`2026-09-0${i + 1}T10:00:00.000Z`),
        },
      });
    }
    const csv = await generateReport(prisma, { tenantId, type: "fees" });
    const lines = csv.trim().split("\n");
    // eslint-disable-next-line no-console
    console.log("[ATK-11.3] CSV lines:", lines.length);
    // The date window is OPTIONAL: with no startDate/endDate the whole
    // ledger is read.
    const all = await generateReport(prisma, { tenantId, type: "fees" });
    expect(all.trim().split("\n").length).toBe(6);
    expect(lines.length).toBe(6);
  });
});
