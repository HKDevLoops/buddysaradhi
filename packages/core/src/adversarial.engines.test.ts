// ADVERSARIAL SUITE — the two ORPHAN ENGINES.
//
// `packages/core/src/engines/invoice.ts` (`generateBatchInvoices`) and
// `packages/core/src/engines/report.ts` (`generateReport`) have ZERO
// production call sites — `grep` finds them only in `packages/core/src/
// index.ts` (the export barrel), their own tests, and the docs. AGENTS.md
// §0.2: "Code that maps to nothing gets deleted." But they are SPEC'd
// (07_Fees_and_Payments.md §4 and §11), so the honest question is not "is it
// dead" but "if a tutor ever pressed the button, would the books lie?".
//
// This suite answers that with EXECUTION, against a real `prisma db push`
// database (the shipped `prisma/schema.prisma`, so the Prisma `Int` money
// ceiling is the real one).
//
// Oracle: 12_Business_Rules.md BR-LED-03/BR-RC-03 (numbers), BR-M-01
// (integer paise), BR-RPT-02 (the ledger report lists direction and void
// status), BR-RPT-04 (the balance formula), BR-SYN-01/02 (outbox in the
// mutation's transaction), BR-FEE-10 (a discount posts a paired
// DISCOUNT_GRANTED credit); 11_Data_Model.md §4; AGENTS.md §3.4 (ORM only),
// §7.3 (never mock the ledger).
import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { randomUUID } from "crypto";
import { execSync } from "child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join, resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { PrismaClient } from "@prisma/client";
import { generateBatchInvoices } from "./engines/invoice";
import { generateReport } from "./engines/report";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO = resolve(__dirname, "../../../");
const SCHEMA = resolve(REPO, "prisma/schema.prisma");

let TEST_DB: string;
let prisma: PrismaClient;
let tmpDir: string;

async function seedTenant(): Promise<string> {
  const tenantId = `adv-${randomUUID()}`;
  await prisma.setting.create({
    data: { tenantId, tenantSecret: randomUUID(), createdAt: new Date() },
  });
  return tenantId;
}

async function seedStudent(tenantId: string, id?: string): Promise<string> {
  const studentId = id ?? randomUUID();
  await prisma.student.create({
    data: {
      id: studentId,
      tenantId,
      firstName: "Batch",
      lastName: "Student",
      admissionDate: "2026-09-01",
      dupKey: `${tenantId}:${studentId}`,
      createdAt: new Date(),
    },
  });
  return studentId;
}

async function seedFeePlan(
  tenantId: string,
  studentId: string,
  baseAmount: number,
): Promise<string> {
  const id = randomUUID();
  await prisma.feePlan.create({
    data: {
      id,
      tenantId,
      studentId,
      model: "postpaid",
      cycle: "monthly",
      baseAmount,
      startDate: "2026-09-01",
      isActive: 1,
      createdAt: new Date(),
    },
  });
  return id;
}

beforeAll(async () => {
  tmpDir = mkdtempSync(join(tmpdir(), "adv-engines-"));
  TEST_DB = join(tmpDir, "adv.db").replace(/\\/g, "/");
  // `--skip-generate`: the Prisma CLIENT is a global artefact under
  // `node_modules/.prisma`, and three test files each running `prisma db
  // push` regenerate it CONCURRENTLY. On a full disk that race leaves a
  // truncated client (and ~1.3 GB of orphaned `.tmp*` engine copies) — it
  // happened during this audit. The client is generated by `prisma generate`
  // (the repo's `postinstall`), so a per-test DATABASE does not need to
  // regenerate it.
  execSync(
    `bunx prisma db push --schema "${SCHEMA}" --accept-data-loss --skip-generate`,
    {
      cwd: REPO,
      stdio: "ignore",
      env: { ...process.env, DATABASE_URL: `file:${TEST_DB}` },
    },
  );
  prisma = new PrismaClient({ datasources: { db: { url: `file:${TEST_DB}` } } });
  await prisma.$connect();
}, 120000);

afterAll(async () => {
  if (prisma) await prisma.$disconnect().catch(() => {});
  for (const ext of ["", "-wal", "-shm", "-journal"]) {
    const p = TEST_DB + ext;
    if (existsSync(p)) rmSync(p, { force: true });
  }
  try {
    rmSync(tmpDir, { recursive: true, force: true });
  } catch {
    /* best-effort */
  }
}, 30000);

