describe("ATTACK 10 — generateBatchInvoices", () => {
  it("ATK-10.1 [P0] a batch invoice posts NO FEE_CHARGED ledger row — the student owes nothing", async () => {
    // The invoice exists (₹1,000, 'unpaid') and `fee_schedule_items` says
    // 'invoiced', but the LEDGER has no FEE_CHARGED row, so
    // `students.balance_paise` stays 0 and the balance the tutor sees is
    // "nothing owed" while the invoice list says "₹1,000 unpaid".
    const tenantId = await seedTenant();
    const studentId = await seedStudent(tenantId);
    await seedFeePlan(tenantId, studentId, 100000);

    const results = await generateBatchInvoices(prisma, {
      tenantId,
      dueDate: "2026-09-30",
      issueDate: "2026-09-01",
      periodLabel: "September 2026",
    });
    expect(results[0]?.status).toBe("success");

    const invoices = await prisma.invoice.findMany({ where: { tenantId } });
    const ledger = await prisma.ledgerEntry.findMany({ where: { tenantId } });
    const student = await prisma.student.findFirst({ where: { id: studentId } });
    // eslint-disable-next-line no-console
    console.log("[ATK-10.1] invoices:", JSON.stringify(invoices.map((i) => ({ n: i.number, t: i.total, s: i.status }))));
    // eslint-disable-next-line no-console
    console.log("[ATK-10.1] ledger rows:", ledger.length);
    // eslint-disable-next-line no-console
    console.log("[ATK-10.1] students.balance_paise:", student?.balancePaise);
    expect(invoices).toHaveLength(1);
    expect(invoices[0]?.total).toBe(100000);
    expect(invoices[0]?.status).toBe("unpaid");
    // BR-LED-02 / BR-RPT-04: a charge that is not in the ledger is not a
    // charge. The invoice and the ledger must agree.
    expect(ledger.length, "the batch invoice must post a FEE_CHARGED ledger row").toBe(1);
    expect(student?.balancePaise).toBe(100000);
  });

  it("ATK-10.2 [P1] two concurrent batch runs allocate the SAME invoice numbers", async () => {
    // `generateBatchInvoices` reads `settings.nextInvoiceSeq` ONCE into JS,
    // hands out numbers from the local copy, and writes the counter back with
    // a plain `db.setting.update` AFTER the batch (engines/invoice.ts:66-71
    // and :196-199). That is a read-modify-write, not an atomic increment
    // (BR-LED-03: "Atomic CTE on sequence columns").
    const tenantId = await seedTenant();
    const studentA = await seedStudent(tenantId);
    const studentB = await seedStudent(tenantId);
    await seedFeePlan(tenantId, studentA, 100000);
    await seedFeePlan(tenantId, studentB, 100000);

    const run = () =>
      generateBatchInvoices(prisma, {
        tenantId,
        dueDate: "2026-09-30",
        issueDate: "2026-09-01",
        periodLabel: "September 2026",
      });
    const [first, second] = await Promise.all([run(), run()]);
    const invoices = await prisma.invoice.findMany({ where: { tenantId } });
    const numbers = invoices.map((i) => i.number);
    // eslint-disable-next-line no-console
    console.log("[ATK-10.2] invoice numbers:", numbers);
    // eslint-disable-next-line no-console
    console.log("[ATK-10.2] results:", JSON.stringify([first, second]));
    const setting = await prisma.setting.findFirst({ where: { tenantId } });
    // eslint-disable-next-line no-console
    console.log("[ATK-10.2] nextInvoiceSeq after:", setting?.nextInvoiceSeq);
    expect(new Set(numbers).size, "invoice numbers must be unique").toBe(numbers.length);
  });

  it("ATK-10.3 [P1] the batch invoice's dates are ISO INSTANTS, so it can never be overdue", async () => {
    // `new Date(issueDate).toISOString()` writes "2026-09-01T00:00:00.000Z"
    // where every other writer writes "2026-09-01". A due_date of
    // "2026-09-30T00:00:00.000Z" is not <= "2026-10-01" as TEXT, so the
    // aging/overdue comparison (BR-RPT-03, BR-REM-02) never fires for a
    // batch invoice.
    const tenantId = await seedTenant();
    const studentId = await seedStudent(tenantId);
    await seedFeePlan(tenantId, studentId, 100000);
    await generateBatchInvoices(prisma, {
      tenantId,
      dueDate: "2026-09-30",
      issueDate: "2026-09-01",
      periodLabel: "September 2026",
    });
    const invoice = await prisma.invoice.findFirst({ where: { tenantId } });
    // eslint-disable-next-line no-console
    console.log("[ATK-10.3] issue_date:", invoice?.issueDate, "due_date:", invoice?.dueDate);
    expect(String(invoice?.dueDate)).toBe("2026-09-30");
  });
});

