// Implements: AGENTS.md §3.5 (one money flow) + RFC-005 (unified payment dialect).
//
// WHY THIS SCRIPT EXISTS. `POST /api/v1/ledger/payment` used to be a third
// money implementation with no invoice attribution. The flow it must run —
// `packages/core/src/feesFlow.ts` — cannot be imported by the Deno gateway:
// core uses extensionless relative imports (`./money`, `./tamper`) that neither
// `deno check` nor the Supabase edge bundler resolves, and migrating core's
// module system for one consumer is out of the question.
//
// So the gateway carries a MECHANICAL copy at
// `apps/gateway/lib/vendor/feesFlow.ts`, regenerated by THIS script — never
// hand-edited. The copy differs from the source in exactly four places, all in
// the import block (verified below by construction, not by review):
//   1. `./money`            -> `./format.ts`  (verified byte-identical paise math)
//   2. `./tamper`           -> `./tamper.ts`  (this script syncs the receipt
//      section too — the old hand vendor lacked computeReceiptTamperHash)
//   3. `type {…} from "./ledger"` -> the LEDGER_ENTRY_TYPES const +
//      LedgerEntryType + Result declarations, extracted textually from
//      `packages/core/src/ledger.ts` (so a new entry type can never go stale
//      here while core grows one)
//   4. `node:crypto` import kept verbatim (Deno-resolvable as written)
//
// Staleness is a TEST failure, not a review discipline:
// `apps/gateway/__tests__/vendor-freshness.test.ts` regenerates in memory and
// fails with the regen command if the disk copy differs. Behavioral drift is a
// second test failure: `ledger-payment-convergence.test.ts` runs core's flow
// and the vendored flow over identical fixtures and asserts identical books.
//
// Usage:
//   bun scripts/sync-vendor-feesflow.ts          # regenerate (writes files)
//   bun scripts/sync-vendor-feesflow.ts --check  # exit 1 + diff stats if stale

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");

const CORE_FLOW = resolve(REPO, "packages/core/src/feesFlow.ts");
const CORE_LEDGER = resolve(REPO, "packages/core/src/ledger.ts");
const CORE_TAMPER = resolve(REPO, "packages/core/src/tamper.ts");
const VENDOR_FLOW = resolve(REPO, "apps/gateway/lib/vendor/feesFlow.ts");
const VENDOR_TAMPER = resolve(REPO, "apps/gateway/lib/vendor/tamper.ts");

function sha256(s: string): string {
  return createHash("sha256").update(s, "utf8").digest("hex");
}

function extractBlock(src: string, startMarker: string, endMarker: string, what: string): string {
  const s = src.indexOf(startMarker);
  if (s < 0) throw new Error(`sync-vendor: ${what} start marker not found`);
  const e = src.indexOf(endMarker, s);
  if (e < 0) throw new Error(`sync-vendor: ${what} end marker not found`);
  return src.slice(s, e + endMarker.length);
}

export interface SyncResult {
  flow: string;
  tamper: string;
  flowHash: string;
  tamperHash: string;
}

export function renderVendored(): SyncResult {
  const flowSrc = readFileSync(CORE_FLOW, "utf8");
  const ledgerSrc = readFileSync(CORE_LEDGER, "utf8");
  const tamperSrc = readFileSync(CORE_TAMPER, "utf8");

  // The two type declarations the flow needs, extracted textually so they
  // cannot drift from core's while this file is regenerated.
  const entryTypes = extractBlock(
    ledgerSrc,
    "export const LEDGER_ENTRY_TYPES = [",
    "] as const;",
    "LEDGER_ENTRY_TYPES",
  );
  const resultType = extractBlock(
    ledgerSrc,
    "export type Result<T, E = Error> =",
    "{ ok: true; value: T } | { ok: false; error: E };",
    "Result<T>",
  );

  // The four import lines, rewritten to vendor-local forms. Everything below
  // the import block travels byte-identical.
  const importBlock = [
    'import { randomUUID } from "node:crypto";',
    'import { paiseAdd, paiseSub } from "./format.ts";',
    'import { computeInvoiceTamperHash, computeReceiptTamperHash } from "./tamper.ts";',
  ].join("\n");

  const flowBodyStart = flowSrc.indexOf("import { randomUUID }");
  if (flowBodyStart < 0) throw new Error("sync-vendor: feesFlow import block not found");
  const firstBlankAfterImports = flowSrc.indexOf("\n\n", flowSrc.indexOf('from "./ledger"'));
  if (firstBlankAfterImports < 0) throw new Error("sync-vendor: feesFlow import block end not found");
  const flowBody = flowSrc.slice(firstBlankAfterImports + 2);

  const flowHash = sha256(flowSrc);
  const flow =
    `// GENERATED by scripts/sync-vendor-feesflow.ts — DO NOT HAND-EDIT.\n` +
    `// Source: packages/core/src/feesFlow.ts @ sha256:${flowHash}\n` +
    `// Regenerate: bun scripts/sync-vendor-feesflow.ts\n` +
    `//\n` +
    `// Mechanical copy: identical to source except the import block (rewritten\n` +
    `// to vendor-local forms, see the script) plus the two type declarations\n` +
    `// below, extracted textually from packages/core/src/ledger.ts. Every if\n` +
    `// about money, every attribution rule, every invariant lives once - here\n` +
    `// by copy, authoritatively in core.\n` +
    `// apps/gateway/__tests__/vendor-freshness.test.ts; behavioral drift fails\n` +
    `// apps/gateway/__tests__/ledger-payment-convergence.test.ts.\n` +
    `${importBlock}\n` +
    `\n` +
    `${entryTypes}\n` +
    `\n` +
    `export type LedgerEntryType = (typeof LEDGER_ENTRY_TYPES)[number];\n` +
    `\n` +
    `${resultType}\n` +
    `\n` +
    flowBody;

  // vendor/tamper.ts becomes a full mechanical copy (it previously lacked the
  // receipt section entirely — the exact incompleteness this script retires).
  const tamperHash = sha256(tamperSrc);
  const tamper =
    `// GENERATED by scripts/sync-vendor-feesflow.ts — DO NOT HAND-EDIT.\n` +
    `// Source: packages/core/src/tamper.ts @ sha256:${tamperHash}\n` +
    `// Regenerate: bun scripts/sync-vendor-feesflow.ts\n` +
    `//\n` +
    `// Full mechanical copy. The verifier contract documented in the source\n` +
    `// (apps/web/src/lib/ledger/tamper-check.ts must agree byte-for-byte)\n` +
    `// applies here unchanged.\n` +
    tamperSrc;

  return { flow, tamper, flowHash, tamperHash };
}

function readDisk(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    // First run: nothing vendored yet. Treat as maximally stale.
    return "";
  }
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const { flow, tamper } = renderVendored();
  const diskFlow = readDisk(VENDOR_FLOW);
  const diskTamper = readDisk(VENDOR_TAMPER);
  if (diskFlow === flow && diskTamper === tamper) {
    console.log("vendor-feesflow: fresh (feesFlow.ts + tamper.ts match core)");
    return;
  }
  if (check) {
    console.error(
      "vendor-feesflow: STALE — regenerate with: bun scripts/sync-vendor-feesflow.ts\n" +
        `  feesFlow.ts: ${diskFlow.length} on disk vs ${flow.length} generated\n` +
        `  tamper.ts: ${diskTamper.length} on disk vs ${tamper.length} generated`,
    );
    process.exit(1);
  }
  writeFileSync(VENDOR_FLOW, flow);
  writeFileSync(VENDOR_TAMPER, tamper);
  console.log("vendor-feesflow: wrote apps/gateway/lib/vendor/feesFlow.ts + tamper.ts");
}

if (import.meta.main) {
  await main();
}
