function resolveContractPath() {
  try {
    return require.resolve("@buddysaradhi/design-system/tokens.json");
  } catch {
    return join(repoRoot, "packages", "design-system", "tokens.json");
  }
}

const contractPath = resolveContractPath();
let contract;
try {
  contract = JSON.parse(readFileSync(contractPath, "utf8"));
} catch (cause) {
  process.stderr.write(`FATAL: cannot read the token contract at ${contractPath}\n`);
  process.stderr.write(`       ${cause instanceof Error ? cause.message : String(cause)}\n`);
  process.exit(1);
}

const problems = [];
const fail = (message) => problems.push(message);

const MATERIAL_IDS = ["minimal", "acrylic", "liquid-glass"];
const DEFAULT_PALETTE_ID = "inked";
const DEFAULT_MATERIAL_ID = "minimal";

if (!Array.isArray(contract.palettes) || contract.palettes.length === 0) {
  fail("tokens.json has no `palettes` array");
}
for (const id of MATERIAL_IDS) {
  if (!contract.materials || !contract.materials[id]) fail(`tokens.json is missing material "${id}"`);
}

const palettes = Array.isArray(contract.palettes) ? contract.palettes : [];
const STRUCTURE_KEYS = palettes.length > 0 ? Object.keys(palettes[0].structure ?? {}) : [];
const MATERIAL_KEYS =
  palettes.length > 0 ? Object.keys(palettes[0].materials?.[DEFAULT_MATERIAL_ID] ?? {}) : [];

const SOLID_PAIRS = [
  ["surface-overlay", "surfaceOverlaySolid"],
  ["surface-nav", "surfaceNavSolid"],
  ["surface-sheet", "surfaceSheetSolid"],
  ["surface-palette", "surfacePaletteSolid"],
];

const seenIds = new Set();
for (const palette of palettes) {
  for (const field of ["id", "name", "tier", "figma", "structure", "materials"]) {
    if (palette[field] === undefined) fail(`palette is missing "${field}"`);
  }
  if (seenIds.has(palette.id)) fail(`duplicate palette id "${palette.id}"`);
  seenIds.add(palette.id);
  if (Object.keys(palette.structure ?? {}).join(",") !== STRUCTURE_KEYS.join(",")) {
    fail(`palette "${palette.id}" has a different structure key set than "${palettes[0].id}"`);
  }
  for (const id of MATERIAL_IDS) {
    const layer = palette.materials?.[id];
    if (!layer) {
      fail(`palette "${palette.id}" is missing material "${id}"`);
      continue;
    }
    if (Object.keys(layer).join(",") !== MATERIAL_KEYS.join(",")) {
      fail(`palette "${palette.id}" material "${id}" has a different key set`);
    }
    for (const [translucent, solidKey] of SOLID_PAIRS) {
      if (!layer[translucent]) fail(`palette "${palette.id}" material "${id}" lacks "${translucent}"`);
      if (!palette.structure?.[solidKey]) {
        fail(`palette "${palette.id}" lacks the paired fallback "${solidKey}"`);
      }
    }
  }
}
if (palettes.length > 0 && !seenIds.has(DEFAULT_PALETTE_ID)) {
  fail(`default palette "${DEFAULT_PALETTE_ID}" is not in the contract`);
}

if (problems.length > 0) {
  process.stderr.write("FATAL: token contract does not satisfy what this generator needs:\n");
  for (const problem of problems) process.stderr.write(`  - ${problem}\n`);
  process.exit(1);
}

