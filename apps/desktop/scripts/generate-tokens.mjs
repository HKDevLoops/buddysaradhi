// Implements: docs/design/overhaul-plan.md §6 — Tauri/desktop token wiring.
//
// WHY A GENERATOR
// `packages/design-system/tokens.json` is the platform contract
// (overhaul-plan §2.2). 20 palettes x 3 material modes is ~1 900 colour values
// and a Tauri window config needs numeric RGB, not CSS. Hand-maintaining both is
// how two platforms end up disagreeing about what "canvas" is. This script is the
// only thing allowed to turn the contract into desktop files.
//
// The colour/CSS/TS mechanics below are intentionally duplicated from
// apps/mobile/scripts/generate-tokens.mjs rather than shared across app
// boundaries: a shared module would have to live in packages/, which no platform
// wave may touch, and an app importing another app's internals is worse. The
// duplication is bounded — the two generated `tokens.css` files must stay
// byte-identical apart from their `Regenerate:` banner line, and the two
// generated `src/theme/tokens.ts` must expose the same exported surface. Both
// are asserted by the diff step in docs/design/platform-tokens.md §7.
//
// INPUT RESOLUTION (documented per the W5 brief)
// apps/desktop does NOT declare `@buddysaradhi/design-system` (verified:
// apps/desktop/node_modules/@buddysaradhi holds only `shared` and `ui`), so the
// contract is read through a path relative to this file:
//   apps/desktop/scripts/../../.. -> repo root -> packages/design-system/tokens.json
// If the workspace package is ever linked, the require.resolve branch takes over.
//
// RUN
//   node apps/desktop/scripts/generate-tokens.mjs
//
// OUTPUTS (all generated, all DO NOT EDIT)
//   apps/desktop/src/styles/tokens.css     the web layer: custom properties with
//                                          the contract names + `-rgb` triplets
//   apps/desktop/src/theme/tokens.ts       typed palette/material/theme surface
//   apps/desktop/src/theme/native.ts       material -> Tauri window-effect map,
//                                          per platform, from this contract
//   apps/desktop/src-tauri/tauri.windows.conf.json
//   apps/desktop/src-tauri/tauri.macos.conf.json
//   apps/desktop/src-tauri/tauri.linux.conf.json
//
// FAIL-CLOSED
// Any shape/contract problem exits 1 and writes NOTHING.
