for (const palette of palettes) {
  for (const materialId of MATERIAL_IDS) {
    const layer = palette.materials[materialId];
    css.push("");
    css.push(`/* ${palette.name} · ${contract.materials[materialId].name} — material layer (text/accent inherited) */`);
    css.push(`[data-palette="${palette.id}"][data-material="${materialId}"] {`);
    for (const [key, value] of Object.entries(layer)) {
      if (CSS_VALUED_MATERIAL_KEYS.has(key)) {
        css.push(`  ${cssVar(key)}: ${value};`);
        continue;
      }
      const at = `${palette.id}/${materialId}/${key}`;
      const channels = parseColor(value, at);
      css.push(`  ${cssVar(key)}: ${toRgbString(channels, at)};`);
      if (channels.a === 1) css.push(`  ${cssVar(key)}-rgb: ${toChannels(channels)};`);
    }
    css.push("}");
  }
}

