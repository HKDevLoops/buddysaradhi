const structureBlock = (palette) =>
  Object.entries(palette.structure)
    .map(([key, value]) => `  ${cssVar(key)}: ${value};`)
    .join("\n");

function rgbTripletBlock(palette) {
  const lines = [];
  for (const [key, value] of Object.entries(palette.structure)) {
    const channels = parseColor(value, `${palette.id}/${key}`);
    if (channels.a !== 1) continue;
    lines.push(`  ${cssVar(key)}-rgb: ${toChannels(channels)};`);
  }
  return lines;
}

