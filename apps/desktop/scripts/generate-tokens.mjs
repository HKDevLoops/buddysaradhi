css.push("    --mat-filter: none;");
css.push("  }");
css.push("}");
css.push("");
css.push("@media (prefers-contrast: more) {");
css.push("  [data-palette] {");
css.push("    --border-default: var(--border-strong);");
css.push("    --text-muted: var(--text-secondary);");
css.push("  }");
css.push("}");

