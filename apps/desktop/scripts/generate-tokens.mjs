function parseColor(value, where) {
  const input = String(value).trim();
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(input);
  if (hex) {
    const body = hex[1];
    const full =
      body.length === 3
        ? body
            .split("")
            .map((c) => c + c)
            .join("")
        : body;
    return {
      r: Number.parseInt(full.slice(0, 2), 16),
      g: Number.parseInt(full.slice(2, 4), 16),
      b: Number.parseInt(full.slice(4, 6), 16),
      a: 1,
    };
  }
  const fn = /^rgba?\(([^)]+)\)$/i.exec(input);
  if (fn) {
    const parts = fn[1].split(/[\s,/]+/).filter(Boolean);
    if (parts.length < 3) fail(`${where}: unparseable colour "${input}"`);
    const [r, g, b, a = "1"] = parts;
    return {
      r: Number.parseInt(r, 10),
      g: Number.parseInt(g, 10),
      b: Number.parseInt(b, 10),
      a: a.endsWith("%") ? Number.parseFloat(a) / 100 : Number.parseFloat(a),
    };
  }
  fail(`${where}: unsupported colour syntax "${input}"`);
  return { r: 0, g: 0, b: 1, a: 1 };
}

/** `#RRGGBB` when opaque, `rgba(r, g, b, a)` otherwise — the same colour, spelled for RN. */
function toRgbString({ r, g, b, a }, where) {
  if (a === 1) {
    /** @param {number} n */
    const hex = (n) => n.toString(16).padStart(2, "0");
    return `#${hex(r)}${hex(g)}${hex(b)}`.toUpperCase();
  }
  if (![r, g, b, a].every((n) => Number.isFinite(n))) fail(`${where}: non-finite channel`);
  return `rgba(${r}, ${g}, ${b}, ${Number.parseFloat(a.toFixed(4))})`;
}

const toChannels = ({ r, g, b }) => `${r} ${g} ${b}`;
/** Tauri `Color` accepts a hex string, so the frame colour is emitted as one. */
const toTauriHex = ({ r, g, b, a }) =>
  `#${[r, g, b]
    .map((n) => n.toString(16).padStart(2, "0"))
    .join("")
    .toUpperCase()}${a === 1 ? "" : Math.round(a * 255).toString(16).padStart(2, "0").toUpperCase()}`;
/** Tauri `Color` also accepts an RGBA array, which is what the window frame needs. */
const toRgbaArray = ({ r, g, b, a }) => [r, g, b, Math.round(a * 255)];

function parseUnit(value, unit, fallback) {
  const match = new RegExp(`^(-?[\\d.]+)${unit}$`).exec(String(value).trim());
  if (!match) {
    fail(`expected "${unit}" unit, received "${value}"`);
    return fallback;
  }
  return Number.parseFloat(match[1]);
}

