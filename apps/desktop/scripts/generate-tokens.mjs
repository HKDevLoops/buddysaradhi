function cssVar(key) {
  const kebab = key
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();
  return `--${kebab}`;
}

function tsKey(cssName) {
  const body = cssName.replace(/^--/, "");
  const camel = body.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(camel) ? camel : body.replace(/-/g, "_");
}

const CSS_VALUED_MATERIAL_KEYS = new Set([
  "mat-blur",
  "mat-saturate",
  "mat-brightness",
  "mat-translucent",
  "mat-border-alpha",
  "mat-specular",
  "mat-fresnel",
  "shadow-overlay",
  "shadow-sheet",
  "mat-filter",
]);
const COLOR_VALUED_MATERIAL_KEYS = new Set([
  "surface-overlay",
  "surface-nav",
  "surface-sheet",
  "surface-palette",
  "surface-scrim",
  "mat-native",
]);
for (const key of MATERIAL_KEYS) {
  if (!CSS_VALUED_MATERIAL_KEYS.has(key) && !COLOR_VALUED_MATERIAL_KEYS.has(key)) {
    fail(`material key "${key}" is neither CSS-typed nor a known colour role`);
  }
}

