/** Zero-pad a sequence to 6 digits — BR-LED-03 / 07 §9.7. */
function padSequence(seq: number): string {
  return String(seq).padStart(6, "0");
}

/**
 * Rule 9 (no silent failures): a rejection that has a defined HTTP status is
 * carried out of the write transaction as a typed error; anything else keeps
 * propagating and becomes a typed 500 upstream.
 */
class LedgerRouteError extends Error {
  readonly status: number;
  constructor(message: string, status: number) {
    super(message);
    this.name = "LedgerRouteError";
    this.status = status;
  }
}

function mapLedgerRouteError(err: unknown): Response {
  if (err instanceof LedgerRouteError) return fail(err.message, err.status);
  throw err;
}

/**
 * Consume one number from the per-tenant sequence and return the prefix to
 * build it with (12_Business_Rules.md BR-LED-03: `receipt_prefix +
 * zero-pad(next_receipt_seq, 6)`; 07_Fees_and_Payments.md §9.7).
 *
 * One statement does increment + RETURNING, so the number is taken atomically
 * inside the caller's write transaction — never read-then-write. The returned
 * value is the post-increment counter (§9.7: `seq = updated nextReceiptSeq -
 * 1`). Gaps are legal and expected (BR-RC-01); the counter is never
 * decremented.
 *
 * P2-3 / BR-SEC-03: the previous statement INSERTed a missing `settings` row,
 * minting a fresh `tenant_secret` for a tenant provisioning never created.
 * `settings` is provisioning state (17_API_Gateway_System.md §5.1,
 * web/03_Auth_and_Provisioning.md Step 7), so a missing row or an absent
 * secret is a typed fail-closed error — never a silently minted key that would
 * sign a hash chain nobody can verify again.
 */
async function takeSequence(
  tx: SqlHandle,
  tenantId: string,
  kind: "receipt" | "invoice",
): Promise<{
  usedSeq: number;
  nextSeq: number;
  prefix: string;
  tenantSecret: string;
}> {
  const now = new Date().toISOString();
  const [seqCol, prefixCol, defaultPrefix] =
    kind === "receipt"
      ? ["next_receipt_seq", "receipt_prefix", "RCP-"]
      : ["next_invoice_seq", "invoice_prefix", "INV-"];

  // Same fail-closed helper the void path uses (10_Security.md §10): it throws
  // when the row is absent or `tenant_secret` is missing/empty, so the key is
  // validated BEFORE any sequence state is touched.
  let tenantSecret: string;
  try {
    tenantSecret = await loadTenantSecret(tx, tenantId);
  } catch (err) {
    const reason = err instanceof Error ? err.message : String(err);
    throw new LedgerRouteError(`tenant_settings_unavailable: ${reason}`, 500);
  }

  const seqStmt = stmtTakeSequence(tenantId, kind, now);
  const row = await oneRow(tx, seqStmt.sql, seqStmt.args);
  if (!row) {
    // Rule 9 — `loadTenantSecret` above proved the row existed, so a missing
    // RETURNING row means it vanished mid-transaction (or the statement never
    // ran). Abort rather than invent a number.
    throw new LedgerRouteError(`could not consume ${kind} sequence for tenant ${tenantId}`, 500);
  }
  const rawPrefix = row[prefixCol];
  const prefix = typeof rawPrefix === "string" && rawPrefix.length > 0 ? rawPrefix : defaultPrefix;
  const nextSeq = Number(row[seqCol]);
  // Rule 7 / BR-SYN-01 — `settings.next_<x>_seq` was just mutated, so the
  // sequence bump replays like every other write. Without this row a lost
  // bump resurfaces as a REUSED receipt/invoice number on the replica
  // (BR-RC-01 / BR-LED-03). Payload via the canonical shared codec
  // (`packages/shared/src/outboxPayload.ts` — P3-11).
  await recordOutbox(
    tx,
    tenantId,
    "settings",
    tenantId,
    "update",
    encodeOutboxPayload("settings", "update", {
      tenant_id: tenantId,
      [seqCol]: nextSeq,
      updated_at: now,
    }).payload,
  );
  return {
    usedSeq: nextSeq - 1,
    nextSeq,
    prefix,
    tenantSecret,
  };
}

/**
 * Write the denormalised `students.balance_paise` cache from inside the same
 * transaction as the ledger entry (packages/core/src/ledger.ts:132 does the
 * same). A zero-row update means the student vanished mid-transaction — abort
 * rather than commit a ledger row with an unsynced cache (Rule 9).
 */
async function syncStudentBalance(
  tx: SqlHandle,
  tenantId: string,
  studentId: string,
  balancePaise: number,
): Promise<void> {
  const now = new Date().toISOString();
  const balanceStmt = stmtSyncStudentBalance(tenantId, studentId, balancePaise, now);
  const res = await run(tx, balanceStmt.sql, balanceStmt.args);
  if (!res.rowsAffected) {
    throw new Error(`student ${studentId} not found inside transaction`);
  }
  // Rule 7 / BR-SYN-01 — `students.balance_paise` was just UPDATEd above, so
  // it gets its own outbox row in the same transaction. The ledger insert is
  // NOT a substitute: a replica that received only the ledger row would show a
  // stale `balance_due` on Students/Attendance until its own recompute ran.
  // Payload via the canonical shared codec (P3-11).
  await recordOutbox(
    tx,
    tenantId,
    "students",
    studentId,
    "update",
    encodeOutboxPayload("students", "update", {
      id: studentId,
      tenant_id: tenantId,
      balance_paise: balancePaise,
      updated_at: now,
    }).payload,
  );
}

// ── Live credits: the reversal graph (BR-RPT-04 [CRITICAL], BR-LED-09) ──────
//
// "Credited" is NOT "this row is not a reversal". The ledger has no
// `reverses_entry_id` column on the ORIGINAL row (11_Data_Model.md §4.13):
// the reversal is the LATER row — a VOID entry carrying `void_of_id` pointing
// back at the row it reverses. So "has this credit been reversed?" is answered
// by looking the OTHER way: a credit is LIVE when no VOID row carries its id.
//
// The predicate this replaces — `void_of_id IS NULL` ON THE CREDIT ROW — reads
// "this row is not itself a reversal", which a VOIDED ORIGINAL also satisfies:
// the receipt the tutor already voided is not a reversal row, so it kept
// counting as money received. That is AUD-001 in packages/core and AUD-014
// here, and the two copies of the rule (core's `sumLiveCredits` and this file)
// must not differ — AGENTS.md §3.5 makes a second copy of the money rule a
// P0 defect, not a convenience.
//
// The read is CHUNKED: SQLite's variable ceiling is 32,766 on the shipped
// libsql build (measured) and 999 on the oldest one, and exceeding it is a
// HARD error, not a truncation — an unchunked `IN (…)` over every credit id
// 500s on a long-lived institute (the same shape `routes/analytics.ts` uses
// and `packages/core`'s `chunkIds` helper exists for).
const MAX_SQL_VARIABLES_PER_STATEMENT = 500;

/** The ids of the credits some later ledger row REVERSED. */
async function reversedCreditIds(orm: PrismaOrm, creditIds: string[]): Promise<Set<string>> {
  const reversed = new Set<string>();
  if (creditIds.length === 0) return reversed;
  for (let i = 0; i < creditIds.length; i += MAX_SQL_VARIABLES_PER_STATEMENT) {
    const chunk = creditIds.slice(i, i + MAX_SQL_VARIABLES_PER_STATEMENT);
    const reversals = await orm.ledgerEntry.findMany({
      where: { type: "VOID", voidOfId: { in: chunk } },
    });
    for (const r of reversals) {
      const target = r.voidOfId;
      if (target !== null && target !== undefined && String(target).length > 0) {
        reversed.add(String(target));
      }
    }
  }
  return reversed;
}

/**
 * Σ the credits that are STILL LIVE against one invoice, in integer paise.
 *
 * `type` narrows the sum: "PAYMENT_RECEIVED" for the BR-LED-09 void guard,
 * null for "every credit" (the invoice's credited total, §9.6 step 5). The
 * `type != 'VOID'` half matters: a VOID row always carries `void_of_id`, so on
 * well-formed data the two agree — but on a row that somehow does not, the
 * mirroring credit of a voided charge would count as money received, and the
 * dialects must not differ there (packages/core/src/ledger.ts `sumLiveCredits`
 * says the same thing about the same edge).
 */
async function liveCreditPaise(
  orm: PrismaOrm,
  invoiceId: string,
  type: string | null,
): Promise<number> {
  const where: Record<string, unknown> = { invoiceId, voidOfId: null };
  if (type === null) where.type = { not: "VOID" };
  else where.type = type;
  const credits = await orm.ledgerEntry.findMany({ where });
  const creditIds = credits.map((c) => String(c.id ?? "")).filter((id) => id.length > 0);
  const reversed = await reversedCreditIds(orm, creditIds);
  // Rule 6 / BR-M-01 — every addend is a safe integer checked by `paiseAdd`,
  // so a corrupt credit can never become NaN money (EC-F-01).
  let sum = 0;
  for (const c of credits) {
    const id = String(c.id ?? "");
    if (id.length > 0 && reversed.has(id)) continue;
    sum = paiseAdd(sum, Number(c.creditPaise ?? 0));
  }
  return sum;
}

// ── F-08: the gateway FeeTx dialect ─────────────────────────────────────────
//
// POST /api/v1/ledger/payment used to be a THIRD money implementation: one
// PAYMENT_RECEIVED row with no invoiceId, no per-invoice attribution, no
// status recompute, no auto-invoice, no fail-closed invariant. A
// gateway-recorded payment reduced the balance but left every invoice unpaid,
// so the dashboard showed tutors chasing fees they had already collected
// (RFC-005).
//
// The fix is NOT a second copy of the attribution loop (AGENTS.md §3.5: the
// money logic lives exactly once, in packages/core/src/feesFlow.ts). It is a
// third DIALECT of the same flow: this factory implements the twelve
// row-level operations of the FeeTx port over the gateway's transaction
// handle, and the payment route hands it to recordPaymentFlow. Every `if`
// about money executes in core; this file decides NOTHING about money, only
// how rows are read and written — the same division the libsql and ORM
// dialects already observe, held by the same parity shape (see
// `ledger-payment-convergence.test.ts`, which asserts the converged behavior
// directly against real SQLite).
//
// Two deliberate non-mirrors, both documented so a future reader does not
// "fix" them back:
//   1. writeSettingsOutbox is a NO-OP: takeSequence (above) already writes
//      the settings replication row when it consumes the number, so writing
//      it again here would double-queue every sequence bump. The guard test
//      ("exactly one settings outbox row per sequence take") pins this.
//   2. writeAudit passes actor "tutor": the port carries no actor (core's own
//      dialects hardcode ACTOR_TUTOR for the same reason), and the migration
//      CHECK constrains actor to tutor/system/sync — a UUID actor would abort
//      the transaction on a migration-built DB.
// Exported for ledger-payment-convergence.test.ts: the test runs THIS factory
// (not a re-implementation) against the vendored flow, so convergence is
// asserted on the shipping adapter rather than a test double of it.
export function gatewayFeeTx(tx: SqlHandle, tenantId: string): FeeTx {
  const txOrm = createPrismaOrm(tx, tenantId);
  return {
    async requireStudent(_tid, studentId) {
      // F5: same typed 404 the route returned before convergence, so the wire
      // contract is unchanged — only the enforcer moved inside the flow.
      const row = await txOrm.student.findFirst({ where: { id: studentId } });
      if (!row) throw new LedgerRouteError("student_not_found", 404);
    },

    requireTenantSecret(tid) {
      // F1 fail-closed: throws when the settings row or secret is absent.
      // Non-async deliberately (deno require-await): returning the promise.
      return loadTenantSecret(tx, tid);
    },

    async takeInvoiceNumber(tid, _now) {
      const s = await takeSequence(tx, tid, "invoice");
      return {
        number: `${s.prefix}${padSequence(s.usedSeq)}`,
        seq: s.usedSeq,
        nextSeq: s.nextSeq,
        prefix: s.prefix,
      };
    },

    async takeReceiptNumber(tid, _now) {
      const s = await takeSequence(tx, tid, "receipt");
      return {
        number: `${s.prefix}${padSequence(s.usedSeq)}`,
        seq: s.usedSeq,
        nextSeq: s.nextSeq,
        prefix: s.prefix,
      };
    },

    async insertReceipt(row) {
      const created = await txOrm.receipt.create({
        data: {
          id: row.receiptId,
          number: row.number,
          ledgerEntryId: row.ledgerEntryId,
          studentId: row.studentId,
          invoiceId: row.invoiceId,
          amount: row.amountPaise,
          paymentMethod: row.paymentMethod,
          paymentRef: row.paymentRef,
          receivedOn: row.receivedOn,
          tamperHash: row.tamperHash,
        },
      });
      // Read back off the INSERTED row (not re-derived): the envelope is a
      // truthful mirror of what committed, byte-shape-identical to core's
      // insertReceiptRow outbox.
      await recordOutbox(
        tx,
        tenantId,
        "receipts",
        String(created.id),
        "insert",
        encodeOutboxPayload("receipts", "insert", {
          id: String(created.id),
          tenant_id: tenantId,
          number: row.number,
          ledger_entry_id: row.ledgerEntryId,
          student_id: row.studentId,
          invoice_id: row.invoiceId,
          amount: row.amountPaise,
          payment_method: row.paymentMethod,
          payment_ref: row.paymentRef,
          received_on: row.receivedOn,
          tamper_hash: row.tamperHash,
          created_at: String(created.createdAt),
          updated_at: String(created.updatedAt),
        }).payload,
      );
    },

    async insertInvoice(row) {
      // subtotal/discount/extraCharges mirror core exactly: a flow-created
      // invoice has no discount lines, so subtotal IS the total. Passing
      // nothing would leave the builder's `?? 0` default writing subtotal 0
      // beside total X — a row that disagrees with itself.
      await txOrm.invoice.create({
        data: {
          id: row.invoiceId,
          number: row.number,
          studentId: row.studentId,
          issueDate: row.issueDate,
          dueDate: row.dueDate,
          subtotal: row.totalPaise,
          discount: 0,
          extraCharges: 0,
          total: row.totalPaise,
          status: row.status,
          tamperHash: row.tamperHash,
        },
      });
      await recordOutbox(
        tx,
        tenantId,
        "invoices",
        row.invoiceId,
        "insert",
        encodeOutboxPayload("invoices", "insert", {
          id: row.invoiceId,
          tenant_id: tenantId,
          number: row.number,
          student_id: row.studentId,
          issue_date: row.issueDate,
          due_date: row.dueDate,
          subtotal: row.totalPaise,
          discount: 0,
          extra_charges: 0,
          total: row.totalPaise,
          status: row.status,
          tamper_hash: row.tamperHash,
          created_at: row.now,
          updated_at: row.now,
        }).payload,
      );
    },

    async setInvoiceStatus({ invoiceId, status, now }) {
      await txOrm.invoice.update({
        where: { id: invoiceId },
        data: { status, updatedAt: now },
      });
      await recordOutbox(
        tx,
        tenantId,
        "invoices",
        invoiceId,
        "update",
        encodeOutboxPayload("invoices", "update", {
          id: invoiceId,
          status,
          updated_at: now,
        }).payload,
      );
    },

    async openInvoices(_tid, studentId) {
      // §9.5: genuinely open statuses only (`overdue` is a display state over
      // an unpaid invoice, so it is open too), voided rows excluded, earliest
      // due first. Identical predicate to the ORM dialect.
      const found = await txOrm.invoice.findMany({
        where: {
          studentId,
          status: { in: ["unpaid", "partial", "overdue"] },
          voidedAt: null,
        },
        orderBy: { dueDate: "asc" },
      });
      return (found as Record<string, unknown>[]).map((r) => ({
        id: String(r.id),
        number: String(r.number),
        total: Number(r.total),
        status: String(r.status),
      }));
    },

    creditedForInvoice(_tid, invoiceId) {
      // §9.6 step 5 — outstanding = total − Σ the credits already attributed
      // to THIS invoice. "Credited" means NOT REVERSED (BR-RPT-04 [CRITICAL]):
      // a voided receipt does NOT count, so the invoice re-opens and the next
      // payment settles it (EC-F-05).
      //
      // The predicate this replaces — `type != 'VOID' AND void_of_id IS NULL`
      // ON THE CREDIT ROW — is true of a VOIDED ORIGINAL (the receipt the tutor
      // already voided is not itself a reversal), so a voided receipt kept
      // counting as money received: the invoice read as settled, the tutor's
      // next payment was swallowed as an overpayment, and the balance drifted
      // (AUD-001 / AUD-014). Core's two dialects already carry the reverse
      // lookup (packages/core/src/fees.ts, feesPrisma.ts); the gateway is a
      // THIRD dialect of the same flow (AGENTS.md §3.5) and must not differ.
      //
      // Summed in JS with paiseAdd (not a SQL SUM) so an overflow or NaN aborts
      // fail-closed instead of silently producing a wrong outstanding — the
      // same guarantee the SQL dialect's COALESCE gives, without adding a new
      // audited builder for one aggregate.
      // Non-async deliberately (deno require-await): returning the promise.
      return liveCreditPaise(txOrm, invoiceId, null);
    },

    async advanceBalance(_tid, studentId) {
      // BR-FEE-15 / 07 §9.1: the advance wallet is DERIVED from the ledger's
      // tags — the credits tagged `[ADVANCE]` minus the debits tagged
      // `[ADVANCE_APPLIED]`. It is not a column and it is not a second opinion
      // about money: this is the row-level sum the flow asks for, and it is
      // the SAME arithmetic as core's two dialects (AGENTS.md §3.5 — a third
      // dialect that disagreed here would give a gateway-recorded charge a
      // different advance than the same charge recorded on the web).
      //
      // The tags are matched as PREFIXES (BR-FEE-04) and a VOIDED row does not
      // count (BR-RPT-04), so a voided advance returns to the wallet and a
      // voided application is un-applied. Summed in JS with paiseAdd/paiseSub
      // (not a SQL SUM) so an overflow or NaN aborts fail-closed.
      const rows = (await txOrm.ledgerEntry.findMany({
        where: { studentId, type: { not: "VOID" }, voidOfId: null },
      })) as Record<string, unknown>[];
      const rowIds = rows.map((row) => String(row.id ?? "")).filter((id) => id.length > 0);
      const reversed = await reversedCreditIds(txOrm, rowIds);
      let advance = 0;
      for (const row of rows) {
        const id = String(row.id ?? "");
        if (id.length > 0 && reversed.has(id)) continue;
        const description =
          row.description === null || row.description === undefined ? "" : String(row.description);
        if (description.startsWith(ADVANCE_TAG)) {
          advance = paiseAdd(advance, Number(row.creditPaise ?? 0));
        }
        if (description.startsWith(ADVANCE_APPLIED_TAG)) {
          advance = paiseSub(advance, Number(row.debitPaise ?? 0));
        }
      }
      return advance;
    },

    async postEntry(input) {
      // Balance formula matches core exactly: (prev + debit) - credit,
      // paise-guarded (throws on unsafe/NaN) where core uses plain arithmetic
      // on already-validated inputs — identical results on valid money,
      // fail-closed on corrupt chain tips (G8).
      const tip = await loadChainTip(tx, tenantId, input.studentId);
      const newBalance = paiseSub(
        paiseAdd(tip.balanceAfterPaise, input.debitPaise),
        input.creditPaise,
      );
      // BR-LED-06: the per-chain logical clock — the new row's `created_at` is
      // strictly greater than the TIP's, so the timestamp order and the link
      // order are the same order and a same-millisecond tie cannot arise.
      const createdAt = nextChainCreatedAtIso(tip.createdAt);
      const secret = await loadTenantSecret(tx, tenantId);
      const entryId = crypto.randomUUID();
      // W5: byte-identical payload + hash stream to core's buildEntryPayload /
      // computeHash (same JSON key order, same sha256(prev?payload?createdAt?
      // secret)), so a gateway-written row verifies under reconcileLedger.
      const thisHash = computeChainHash(
        tip.prevHash,
        ledgerEntryPayload({
          id: entryId,
          studentId: input.studentId,
          type: input.type,
          debitPaise: input.debitPaise,
          creditPaise: input.creditPaise,
          balanceAfterPaise: newBalance,
          occurredOn: input.occurredOn,
        }),
        createdAt,
        secret,
      );
      const le = await txOrm.ledgerEntry.create({
        data: {
          id: entryId,
          studentId: input.studentId,
          invoiceId: input.invoiceId,
          type: input.type,
          debitPaise: input.debitPaise,
          creditPaise: input.creditPaise,
          balanceAfterPaise: newBalance,
          description: input.description,
          occurredOn: input.occurredOn,
          source: "gateway",
          prevHash: tip.prevHash,
          thisHash,
          createdAt,
        },
      });
      await syncStudentBalance(tx, tenantId, input.studentId, newBalance);
      // Full-row outbox like core's postLedgerEntry (not the old minimal
      // {type, receiptNo} shape, from which no replica could rebuild the
      // row). No replay reader exists yet, so this converges the shape before
      // one is built rather than after.
      await recordOutbox(
        tx,
        tenantId,
        "ledger_entries",
        String(le.id),
        "insert",
        encodeOutboxPayload("ledger_entries", "insert", {
          ...(le as unknown as Record<string, unknown>),
        }).payload,
      );
      return String(le.id);
    },

    async writeAudit(args) {
      await recordAudit(
        tx,
        tenantId,
        "tutor",
        args.action,
        args.refType,
        args.refId,
        args.metadata,
      );
    },

    async writeSettingsOutbox() {
      // Intentionally a no-op: takeSequence (takeInvoiceNumber /
      // takeReceiptNumber above) already queued the settings replication row
      // when it consumed the number, so writing it again here would
      // double-queue every sequence bump. The guard test ("exactly one
      // settings outbox row per sequence take") pins this.
    },
  };
}

/**
 * BR-SEC-04 — the void route's PIN gate.
 *
 * WHY THE EDGE HAS TO CHECK IT. The ledger is append-only (Rule 1), so a void
 * is the ONLY correction path a mistaken payment has (07_Fees_and_Payments.md
 * §9.10, 12_Business_Rules.md BR-LED-04). The web's server action verified the
 * PIN with argon2id before it called this route — a CALLER-side control on a
 * route the gateway itself exposes. A stolen session could post a void with
 * no PIN material at all, and the tutor's books would read as unpaid with no
 * correction left to make. The gateway's own attendance route states the
 * principle: "A client-side check is not a sufficient control".
 *
 * WHY A PROOF AND NOT THE PIN. `settings.pin_hash` is argon2id(m=64MiB) and
 * the Deno edge has no argon2 (WebCrypto offers PBKDF2/SHKDF only). What the
 * edge CAN compute is `settings.pin_proof` — an HMAC over the PIN under a
 * server-side key (`lib/crypto.ts` `pinProof`), the same machinery the
 * secure-erase gate uses (routes/security.ts, 10_Security.md §18.1). The
 * proof is a DERIVED value: it proves knowledge of the PIN without the PIN
 * and without the PIN crossing the wire (BR-SEC-07).
 *
 * THE REFUSALS, each fail-closed and each typed:
 *   1. no PIN configured    → there is nothing to confirm against (403)
 *   2. no proof on record   → the tutor must re-confirm their PIN once (403)
 *   3. no proof offered     → the request carried none (403)
 *   4. the proof does not match → the PIN was wrong (401)
 *
 * The wrong-PIN and no-PIN answers are deliberately DIFFERENT statuses: a
 * wrong PIN is a failed authentication (401) and a missing proof is a
 * request that cannot be authorised at all (403). Neither answer says
 * anything about the stored proof itself.
 */
async function assertVoidPinProof(
  db: SqlHandle,
  tenantId: string,
  offeredProof: unknown,
): Promise<void> {
  const pinStmt = stmtSettingPinProof(tenantId);
  const pinRow = await oneRow(
    // SAFETY: `SqlHandle` is the only capability this route uses; `DB` (the
    // libsql client) satisfies it structurally — the same cast the erase
    // route makes (routes/security.ts).
    db as unknown as SqlHandle,
    pinStmt.sql,
    pinStmt.args,
  );

  const pinConfigured = typeof pinRow?.pin_hash === "string" && pinRow.pin_hash.length > 0;
  if (!pinConfigured) {
    logWarn("ledger.void_pin_unset", { tenantId });
    throw new LedgerRouteError(
      "PIN_PROOF_UNAVAILABLE: no PIN is configured for this account. Set a " +
        "security PIN in Settings → Security, then void again. (BR-SEC-04.)",
      403,
    );
  }

  const storedProof = typeof pinRow?.pin_proof === "string" ? pinRow.pin_proof : "";
  if (storedProof.length === 0) {
    logWarn("ledger.void_pin_proof_unset", { tenantId });
    throw new LedgerRouteError(
      "PIN_PROOF_UNAVAILABLE: re-confirm your security PIN in Settings → " +
        "Security, then void again. The edge verifies the PIN without ever " +
        "seeing it. (10_Security.md §18.1, BR-SEC-04.)",
      403,
    );
  }

  const offered = typeof offeredProof === "string" ? offeredProof.trim() : "";
  if (offered.length === 0) {
    logWarn("ledger.void_pin_proof_missing", { tenantId });
    throw new LedgerRouteError(
      "PIN_PROOF_UNAVAILABLE: a PIN confirmation is required to void a " +
        "receipt. (10_Security.md §18.1, BR-SEC-04.)",
      403,
    );
  }

  // Bound the input BEFORE the constant-time comparison. `constantTimeCompare`
  // iterates the longer of the two operands, so an unbounded caller-supplied
  // string would be walked character by character — a megabyte POST becomes a
  // megabyte of pointless CPU on the ledger's correction path. The length
  // check is also what keeps a wrong-length proof from being compared at all.
  if (offered.length !== storedProof.length) {
    logWarn("ledger.void_pin_proof_malformed", { tenantId });
    throw new LedgerRouteError(
      "PIN_PROOF_MISMATCH: that PIN confirmation was not accepted. Nothing " +
        "was written. (BR-SEC-04.)",
      401,
    );
  }
  if (!constantTimeCompare(storedProof, offered)) {
    logWarn("ledger.void_pin_proof_mismatch", { tenantId });
    throw new LedgerRouteError(
      "PIN_PROOF_MISMATCH: that PIN confirmation was not accepted. Nothing " +
        "was written. (BR-SEC-04.)",
      401,
    );
  }
}

export const handleLedger: RouteHandler = async (req, db, tenantId, path, method, url) => {
  const sp = url.searchParams;
  const orm = createPrismaOrm(db, tenantId);

  // GET /api/v1/ledger
  if (path === "/api/v1/ledger" && method === "GET") {
    const studentId = sp.get("studentId");
    const rows = await orm.ledgerEntry.findMany({
      where: studentId ? { studentId } : {},
      orderBy: { occurredOn: "desc" },
      take: 200,
    });

    // EC-F-05 / BR-LED-03 — `isVoid` marks the row that a LATER row reverses, so
    // the screen can strike it through and stop offering to void it again.
    //
    // The web client already declared this field
    // (apps/web/src/server/queries/fees.ts) and branched on it
    // (ledger-table.tsx), but this response never sent it, so `isVoid` was
    // ALWAYS undefined on screen: a receipt that had been voided rendered
    // exactly like a live one, strike-through and all, and still carried an
    // enabled "Void" button. 07 §6.3 and §10.2 BR-LED-03 both require the
    // original to be visibly struck with a "voided by" link — this is the fact
    // that makes that possible.
    //
    // Derived from the rows already in hand (no extra query, no extra request):
    // a row is voided iff some OTHER row in the set carries it as `void_of_id`.
    // The reversing row itself is identified by `reverses_entry_id` (already in
    // the payload) and is NOT `isVoid` — it is a real, live correcting entry, and
    // striking IT through would hide the audit trail the rule is protecting.
    //
    // Key spelling: this field is camelCase while the rest of the envelope is
    // snake_case. That inconsistency is pre-existing (the client's declared row
    // type names `isVoid`); renaming it is a contract change across three files
    // for no behaviour gain, so the declared name wins.
    const reversedEntryIds = new Set<string>();
    for (const e of rows) {
      const target = e.voidOfId;
      if (typeof target === "string" && target.length > 0) reversedEntryIds.add(target);
    }

    return ok(
      rows.map((e) => ({
        id: e.id,
        tenant_id: tenantId,
        student_id: e.studentId,
        type: e.type,
        debit: e.debitPaise,
        credit: e.creditPaise,
        balance_after: e.balanceAfterPaise,
        method: e.paymentMethod,
        description: e.description,
        occurred_on: e.occurredOn,
        invoice_id: e.invoiceId,
        receipt_no: e.receiptNo,
        reverses_entry_id: e.voidOfId,
        isVoid: reversedEntryIds.has(String(e.id)),
        this_hash: e.thisHash,
      })),
    );
  }

  // GET /api/v1/ledger/invoices
  if (path === "/api/v1/ledger/invoices" && method === "GET") {
    const studentId = sp.get("studentId");
    const invs = await orm.invoice.findMany({
      where: studentId ? { studentId } : {},
      take: 100,
    });

    // BR-LED-06 read consistency + BR-RPT-04 [CRITICAL]: a credit counts only
    // while it has NOT been reversed. "Reversed" is the REVERSE LOOKUP — some
    // later VOID row carries this credit's id — not "this row is not itself a
    // reversal", which a VOIDED ORIGINAL also satisfies. The predicate this
    // replaces kept counting a voided receipt as money received, so an invoice
    // whose payment had been voided read as still paid (AUD-001 / AUD-014).
    // Mirrors the money flow's own filter (packages/core/src/feesFlow.ts,
    // fees.ts, feesPrisma.ts).
    const entries = await orm.ledgerEntry.findMany({
      where: { type: "PAYMENT_RECEIVED", voidOfId: null },
      take: 200,
    });
    const reversed = await reversedCreditIds(
      orm,
      entries.map((e) => String(e.id ?? "")).filter((id) => id.length > 0),
    );

    const paidMap = new Map<string, number>();
    for (const e of entries) {
      // Defence-in-depth: skip any VOID or reversal-linked row that reached us
      // despite the query filter (see above), and any credit a later VOID row
      // reverses.
      if (e.type === "VOID" || e.voidOfId != null) continue;
      const id = String(e.id ?? "");
      if (id.length > 0 && reversed.has(id)) continue;
      if (e.invoiceId) {
        const key = String(e.invoiceId);
        // Rule 6 / BR-M-01 — integer paise, never a float sum.
        paidMap.set(key, paiseAdd(paidMap.get(key) ?? 0, Number(e.creditPaise ?? 0)));
      }
    }

    const data = invs.map((inv) => ({
      id: inv.id,
      tenant_id: tenantId,
      number: inv.number,
      student_id: inv.studentId,
      issue_date: inv.issueDate,
      due_date: inv.dueDate,
      subtotal: inv.subtotal,
      total: inv.total,
      status: inv.status,
      paid_amount_minor: paidMap.get(inv.id) ?? 0,
    }));
    return ok(data);
  }

  // GET /api/v1/ledger/fees
  //
  // ── Roster paging, on the same seam as GET /api/v1/students ──────────────
  // (routes/students.ts:205-208): `page`/`pageSize`, `orderBy` validated by
  // the `resolveOrderBy` allowlist in lib/orm.ts, and the population size from
  // the audited `stmtCountWhere` behind `orm.student.count`. No caller string
  // ever reaches SQL text (AGENTS.md §3.4).
  //
  // The previous read was `take: 200` with no total, no pager and no warning:
  // students 201+ were unreachable from Fees, Pending/Overdue and Collections,
  // and nothing in the response hinted that anything was missing. The defect is
  // the SILENCE, so the fix is that the population size is now always in the
  // response and a page is something the caller asked for.
  //
  // `data` deliberately stays the ARRAY that `getStudentsForFees`
  // (apps/web/src/server/queries/fees.ts:12) and the three Fees surfaces it
  // feeds already consume, so nothing breaks at the same time as the fix; the
  // paging facts ride beside it in the envelope, next to `success`, which is
  // where this gateway already puts read metadata. A caller that sends no
  // pager gets the COMPLETE roster (no cap) — the existing readers stop losing
  // students — and a caller that sends a pager gets a page plus the total.
  if (path === "/api/v1/ledger/fees" && method === "GET") {
    const search = (sp.get("search") ?? "").toLowerCase();
    const paged = sp.has("page") || sp.has("pageSize");
    const page = Math.max(1, parseInt(sp.get("page") ?? "1", 10) || 1);
    const pageSize = Math.min(200, Math.max(1, parseInt(sp.get("pageSize") ?? "200", 10) || 200));
    const from = (page - 1) * pageSize;

    const where = { status: "active", archivedAt: null };
    const rawStudents = await orm.student.findMany({
      where,
      orderBy: { firstName: "asc" },
      // Search is a substring match applied in the route (the builder has no
      // LIKE operator), so a searched read has to be complete before it can be
      // sliced. Unsearched reads let SQLite do the paging.
      ...(paged ? (search ? {} : { take: pageSize, skip: from }) : {}),
    });

    const matched = search
      ? rawStudents.filter(
          (s) =>
            (s.firstName && s.firstName.toLowerCase().includes(search)) ||
            (s.lastName && s.lastName.toLowerCase().includes(search)) ||
            (s.code && s.code.toLowerCase().includes(search)),
        )
      : rawStudents;

    const pageRows = paged && search ? matched.slice(from, from + pageSize) : matched;

    const total = search ? matched.length : await orm.student.count({ where });

    const students = pageRows.map((s) => ({
      id: s.id,
      name: `${s.firstName || ""} ${s.lastName || ""}`.trim(),
      code: s.code,
      fee_model: s.feeModel || "postpaid",
      balance_due: s.balancePaise || 0,
    }));

    return json({
      success: true,
      data: students,
      total,
      page: paged ? page : 1,
      /** The size of the slice actually returned, so an unpaged read reports
       *  its own row count rather than a page size that was never applied. */
      pageSize: paged ? pageSize : students.length,
      totalPages: paged ? Math.max(1, Math.ceil(total / pageSize)) : 1,
      truncated: paged && students.length < total,
    });
  }

  // POST /api/v1/ledger/payment
  if (path === "/api/v1/ledger/payment" && method === "POST") {
    // RFC-004 C1 — fail-closed behind the index.ts middleware (the key is also
    // needed below for the in-transaction store).
    const idemKey = requireIdempotencyKey(req);
    if (idemKey instanceof Response) return idemKey;
    const idemRoute = idempotencyRoute(method, path);
    const body = await req.json().catch(() => ({}));
    // amountPaise is the contracts/openapi.yaml name; amount / amount_minor are
    // the historical spellings this route already accepted.
    const parsed = LedgerPaymentSchema.safeParse({
      studentId: body.studentId ?? body.student_id,
      amount: body.amountPaise ?? body.amount ?? body.amount_minor,
      method: body.method ?? body.payment_method,
      occurredOn: body.occurredOn ?? body.occurred_on,
      description: body.description,
      reference: body.reference ?? body.payment_ref,
    });
    if (!parsed.success) return failZod(parsed.error);
    const studentId = parsed.data.studentId;
    const credit = parsed.data.amount;
    const paymentMethod = parsed.data.method ?? "upi";
    const occurredOn = parsed.data.occurredOn ?? new Date().toISOString().slice(0, 10);
    const description = parsed.data.description ?? "Payment received";
    const reference = parsed.data.reference ?? "";

    // F-08: the student-existence check moved INSIDE the flow
    // (requireStudent), which returns the same typed 404 — one enforcement
    // point instead of two. `now` is a single timestamp for the whole
    // payment; every row the flow writes carries it.
    const now = new Date().toISOString();

    try {
      const result = await withWriteTransaction(db, async (tx) => {
        // F-08: no attribution logic lives here anymore. The gateway FeeTx
        // dialect above adapts this transaction to the port, and
        // recordPaymentFlow — the SAME flow the web path runs — decides
        // per-invoice attribution, status recompute, remainder
        // auto-invoice and the fail-closed creditedPaise invariant.
        const flow = await recordPaymentFlow(
          gatewayFeeTx(tx, tenantId),
          {
            tenantId,
            studentId,
            amountPaise: credit,
            description,
            receivedOn: occurredOn,
            method: paymentMethod,
            reference,
          },
          now,
        );
        // The flow synced the balance on every posted entry, so the chain
        // tip IS the new balance. Read inside the same transaction (G2).
        const tip = await loadChainTip(tx, tenantId, studentId);
        const payload = { ok: true, receiptNo: flow.receiptNo, newBalance: tip.balanceAfterPaise };
        const env = okEnvelope(200, payload);
        await storeIdempotentResponse(tx, tenantId, idemRoute, idemKey, env.code, env.body);
        return payload;
      });
      // Cache invalidation follows COMMIT (BR-SYN-01): a rolled-back
      // transaction left the rows untouched, so the cached GET is still
      // correct, while a committed one must never keep serving the
      // pre-mutation response.
      invalidateTenant(tenantId);
      return ok(result);
    } catch (err) {
      // RFC-004 K2/K3 — a concurrent duplicate committed first: this
      // transaction rolled back, so replay the winner's stored bytes.
      const replay = await replayIfDuplicate(db, tenantId, idemRoute, idemKey, err);
      if (replay) return replay;
      return mapLedgerRouteError(err);
    }
  }

  // POST /api/v1/ledger/invoice
  if (path === "/api/v1/ledger/invoice" && method === "POST") {
    // RFC-004 C1 — fail-closed (see the payment path).
    const idemKey = requireIdempotencyKey(req);
    if (idemKey instanceof Response) return idemKey;
    const idemRoute = idempotencyRoute(method, path);
    const body = await req.json().catch(() => ({}));
    // amountPaise is the contracts/openapi.yaml name; amount / amount_minor are
    // the historical spellings this route already accepted.
    const parsed = LedgerInvoiceSchema.safeParse({
      studentId: body.studentId ?? body.student_id,
      amount: body.amountPaise ?? body.amount ?? body.amount_minor,
      number: body.number,
      issueDate: body.issueDate ?? body.issue_date,
      dueDate: body.dueDate ?? body.due_date,
      occurredOn: body.occurredOn ?? body.occurred_on,
      description: body.description,
    });
    if (!parsed.success) return failZod(parsed.error);
    const studentId = parsed.data.studentId;
    const amount = parsed.data.amount;
    const description = parsed.data.description ?? "Fee charged";

    const stu = await orm.student.findFirst({ where: { id: studentId } });
    if (!stu) return fail("student_not_found", 404);

    try {
      const result = await withWriteTransaction(db, async (tx) => {
        const txOrm = createPrismaOrm(tx, tenantId);

        const tip = await loadChainTip(tx, tenantId, studentId);
        // Rule 6 / BR-M-01 — guarded paise addition (overflow is a typed
        // throw, never an `Infinity` balance).
        const newBalance = paiseAdd(tip.balanceAfterPaise, amount);

        // G3 / BR-LED-03: numbers come from `settings.next_invoice_seq`, one
        // atomic increment per invoice (07 §9.7). An explicit client `number`
        // still consumes a sequence so a later auto number can never collide
        // with it — the counter is never decremented (BR-RC-01).
        const seq = await takeSequence(tx, tenantId, "invoice");
        const invNo = parsed.data.number ?? `${seq.prefix}${padSequence(seq.usedSeq)}`;
        const issueDate = parsed.data.issueDate ?? new Date().toISOString().slice(0, 10);

        // 10_Security.md §10 / 11_Data_Model.md §4.12 — `tamper_hash` is NOT
        // NULL and must be the CANONICAL bytes the web verifier recomputes
        // (`apps/web/src/lib/ledger/tamper-check.ts:22`), so it is built from
        // the shared `computeInvoiceTamperHash`, not re-derived here. Writing
        // the invoice without it would make every gateway invoice read as
        // tampered the moment a tutor runs Diagnostics.
        const tamperHash = computeInvoiceTamperHash(
          { number: invNo, studentId, totalPaise: amount, issueDate },
          seq.tenantSecret,
        );

        const inv = await txOrm.invoice.create({
          data: {
            number: invNo,
            studentId,
            issueDate,
            dueDate: parsed.data.dueDate ?? null,
            subtotal: amount,
            total: amount,
            status: "unpaid",
            tamperHash,
          },
        });

        const entryId = crypto.randomUUID();
        // BR-LED-06: the per-chain logical clock (see `postEntry` above).
        const createdAt = nextChainCreatedAtIso(tip.createdAt);
        const occurredOn = parsed.data.occurredOn ?? createdAt.slice(0, 10);
        const thisHash = computeChainHash(
          tip.prevHash,
          ledgerEntryPayload({
            id: entryId,
            studentId,
            type: "FEE_CHARGED",
            debitPaise: amount,
            creditPaise: 0,
            balanceAfterPaise: newBalance,
            occurredOn,
          }),
          createdAt,
          seq.tenantSecret,
        );

        const le = await txOrm.ledgerEntry.create({
          data: {
            id: entryId,
            studentId,
            invoiceId: inv.id,
            type: "FEE_CHARGED",
            debitPaise: amount,
            creditPaise: 0,
            balanceAfterPaise: newBalance,
            description,
            occurredOn,
            source: "gateway",
            prevHash: tip.prevHash,
            thisHash,
            createdAt,
          },
        });

        await syncStudentBalance(tx, tenantId, studentId, newBalance);

        await recordOutbox(
          tx,
          tenantId,
          "ledger_entries",
          le.id,
          "create",
          encodeOutboxPayload("ledger_entries", "create", {
            type: "invoice",
            invoiceNo: invNo,
          }).payload,
        );
        // Rule 7 / BR-SYN-01 — `invoices` is a distinct mutated table; its
        // outbox row carries the spec §4.12 columns (including the tamper
        // evidence) so the replica's Fees screen can render the invoice
        // without re-deriving it from the ledger.
        await recordOutbox(
          tx,
          tenantId,
          "invoices",
          inv.id,
          "create",
          encodeOutboxPayload("invoices", "create", {
            id: inv.id,
            tenant_id: tenantId,
            number: invNo,
            student_id: studentId,
            issue_date: issueDate,
            due_date: parsed.data.dueDate ?? null,
            subtotal: amount,
            discount: 0,
            extra_charges: 0,
            total: amount,
            status: "unpaid",
            tamper_hash: tamperHash,
          }).payload,
        );
        await recordAudit(tx, tenantId, tenantId, "ledger.invoice", "student", studentId, {
          amount,
          invoiceNo: invNo,
        });
        // RFC-004 C1 — response bytes commit atomically with the invoice (see
        // the payment path).
        const payload = { ok: true, invoiceId: inv.id, newBalance };
        const env = okEnvelope(200, payload);
        await storeIdempotentResponse(tx, tenantId, idemRoute, idemKey, env.code, env.body);
        return payload;
      });
      // Cache invalidation follows COMMIT — see the payment path.
      invalidateTenant(tenantId);
      return ok(result);
    } catch (err) {
      // RFC-004 K2/K3 — concurrent-duplicate race (see the payment path).
      const replay = await replayIfDuplicate(db, tenantId, idemRoute, idemKey, err);
      if (replay) return replay;
      return mapLedgerRouteError(err);
    }
  }

  // POST /api/v1/ledger/void
  if (path === "/api/v1/ledger/void" && method === "POST") {
    // RFC-004 C1 — fail-closed (see the payment path).
    const idemKey = requireIdempotencyKey(req);
    if (idemKey instanceof Response) return idemKey;
    const idemRoute = idempotencyRoute(method, path);
    const body = await req.json().catch(() => ({}));
    const parsed = LedgerVoidSchema.safeParse({
      entryId: body.entryId ?? body.entryIdToVoid,
      reason: body.reason,
      // The PIN proof, in either spelling: `pinProof` is the erase route's
      // (and the contract's) name, `pin_proof` is the settings sync-apply
      // route's — the same two-spelling affordance the contract already
      // documents for that route.
      pinProof: body.pinProof ?? body.pin_proof,
    });
    if (!parsed.success) return failZod(parsed.error);
    const entryId = parsed.data.entryId;
    const reason = parsed.data.reason;

    try {
      // BR-SEC-04 — the PIN gate, BEFORE anything is written. It runs outside
      // the write transaction so a refused void never takes the tenant's write
      // lock, and it throws the route's typed error, so the refusal is a
      // 401/403 with a dispatch code rather than a 500.
      await assertVoidPinProof(db, tenantId, parsed.data.pinProof);

      const result = await withWriteTransaction(db, async (tx) => {
        const txOrm = createPrismaOrm(tx, tenantId);

        const entries = await txOrm.ledgerEntry.findMany({ where: { id: entryId } });
        const entry = entries[0];
        if (!entry) throw new LedgerRouteError("entry_not_found", 404);

        // BR-LED-05 — a VOID entry cannot itself be voided.
        if (entry.type === "VOID") {
          throw new LedgerRouteError("cannot_void_a_void_entry", 409);
        }
        // BR-LED-04 — double-void is a conflict, not a second reversing row.
        const prior = await txOrm.ledgerEntry.findMany({
          where: { voidOfId: entryId },
          take: 1,
        });
        if (prior.length > 0) {
          throw new LedgerRouteError("entry_already_voided", 409);
        }

        // BR-LED-09 [12_Business_Rules.md] — "Voiding a FEE_CHARGED is
        // permitted only if no PAYMENT_RECEIVED credits it." Enforced here, in
        // the transaction, because the ledger is append-only (Rule 1): a void is
        // the ONLY correction path, so a refused void that gets through leaves
        // the books permanently wrong with no further correction available.
        //
        // What it prevented: reversing a charge that ₹3,000 of payments already
        // settle. The reversal restores the balance (it mirrors the debit), but
        // those credits have nothing to credit any more — the invoice still
        // reads `paid` while its `paid_amount_minor` no longer covers its total,
        // i.e. exactly the "orphan credits; balances drift" failure the rule
        // names. 07 §10.2 BR-LED-04 and EC-F-06 give the same rule as the UI
        // half of the contract: "Void those receipts first."
        //
        // WHAT COUNTS AS A CREDIT — the reversal graph, not the row's own
        // `void_of_id` (AUD-014). The old predicate was
        // `voidOfId: null` ON THE CREDIT ROW, which reads "this row is not
        // itself a reversal" — and a payment the tutor ALREADY voided is not a
        // reversal row either (the reversal is the LATER row that points back
        // at it). So the voided receipt kept counting as a live credit and
        // kept blocking the charge: the tutor was told "void those receipts
        // first" about a receipt they had already voided, and on an append-only
        // ledger that closes the correction path for good (the fee stays on the
        // books forever). A receipt that is still LIVE does count, and the void
        // is refused — and the refusal writes NOTHING: this guard runs before
        // the audit row, the reversing row and every outbox row, so the throw
        // rolls the transaction back.
        //
        // An ad-hoc charge with no invoice has no credit set to protect, so
        // there is nothing to check and the void proceeds.
        if (
          entry.type === "FEE_CHARGED" &&
          typeof entry.invoiceId === "string" &&
          entry.invoiceId.length > 0
        ) {
          const livePayments = await liveCreditPaise(txOrm, entry.invoiceId, "PAYMENT_RECEIVED");
          if (livePayments > 0) {
            // The engine's wording is the reference (packages/core/src/ledger.ts
            // `voidLedgerFlow`): the typed code first, then the tutor-facing
            // half of EC-F-06 — "void those receipts first". The web maps this
            // code to its own one-liner (apps/web/src/server/actions/fees.ts
            // `mapVoidGatewayError`).
            throw new LedgerRouteError(
              `CHARGE_HAS_CREDITS: this fee has ${livePayments} paise of live payments against it — void those receipts first, then void the fee (BR-LED-09).`,
              409,
            );
          }
        }

        // 07 §9.10 step 1 — audit first: if the audit write fails the whole
        // transaction aborts (fail-closed, 10_Security.md §4). Metadata now
        // carries the reason (audit finding G4).
        await recordAudit(tx, tenantId, tenantId, "ledger.void", "ledger", entryId, {
          reason,
          original_type: entry.type,
          // BR-SEC-08 — the audit row records that this sensitive action was
          // RE-AUTHORISED, not merely that it happened.
          pin_verified: true,
        });

        const tip = await loadChainTip(tx, tenantId, entry.studentId);

        // BR-LED-06 — a FORK is an integrity violation, and it is REPORTED.
        //
        // The chain of one student is a linked list, and the links are the
        // order. Two rows claiming the same predecessor are not an ordering
        // artefact to be broken by a tie-break: they are two histories, and
        // extending one of them silently would make the books a guess. So the
        // void path WALKS the links first and writes the violation to the
        // audit log (10_Security.md §9.4, the same action the web's
        // Diagnostics writes) — the finding is recorded, never resolved.
        //
        // The void still PROCEEDS. The ledger is append-only (Rule 1), so a
        // void is the ONLY correction path a tutor has; refusing it over a
        // structural finding would leave the books permanently wrong with no
        // further correction available (BR-LED-09's own argument, inverted).
        const chainReport = await verifyChainLinks(tx, tenantId, entry.studentId);
        if (chainReport.fork !== null || chainReport.unreachable.length > 0) {
          await recordAudit(
            tx,
            tenantId,
            "system",
            "ledger_integrity_violation",
            "ledger_entries",
            entry.studentId,
            {
              violation: chainReport.fork !== null ? "chain_fork" : "chain_unreachable_rows",
              forked_predecessor: chainReport.fork?.prevHash ?? null,
              forked_rows: chainReport.fork?.rowIds ?? [],
              unreachable_rows: chainReport.unreachable,
              timestamp_ties: chainReport.timestampTies,
              rule: "BR-LED-06",
            },
          );
        }

        // BR-LED-04 — mirror BOTH directions (equal amount, opposite sign),
        // so voiding a FEE_CHARGED reverses the debit instead of posting a
        // net-zero row that reports success (audit finding G4).
        const debit = Number(entry.creditPaise ?? 0);
        const credit = Number(entry.debitPaise ?? 0);
        // Rule 6 / BR-M-01 — mirrored amounts are still money: guard the
        // arithmetic so a corrupt tip/debit/credit yields a typed throw
        // instead of NaN on the reversing row (which would break the chain).
        const newBalance = paiseSub(paiseAdd(tip.balanceAfterPaise, debit), credit);

        const tenantSecret = await loadTenantSecret(tx, tenantId);
        const voidEntryId = crypto.randomUUID();
        // BR-LED-06: the per-chain logical clock (see `postEntry` above).
        const createdAt = nextChainCreatedAtIso(tip.createdAt);
        // 07 §9.10: the reversing row is dated the day it is written.
        const occurredOn = createdAt.slice(0, 10);
        const thisHash = computeChainHash(
          tip.prevHash,
          ledgerEntryPayload({
            id: voidEntryId,
            studentId: entry.studentId,
            type: "VOID",
            debitPaise: debit,
            creditPaise: credit,
            balanceAfterPaise: newBalance,
            occurredOn,
          }),
          createdAt,
          tenantSecret,
        );

        // Enforces Rule 1 (Void is a new reversing ledger entry)
        const voidRow = await txOrm.ledgerEntry.create({
          data: {
            id: voidEntryId,
            studentId: entry.studentId,
            type: "VOID",
            debitPaise: debit,
            creditPaise: credit,
            balanceAfterPaise: newBalance,
            description: `VOID: ${reason}`,
            occurredOn,
            voidOfId: entryId,
            source: "gateway",
            prevHash: tip.prevHash,
            thisHash,
            createdAt,
          },
        });

        await syncStudentBalance(tx, tenantId, entry.studentId, newBalance);

        // EC-F-05 - mark the receipt voided in the same transaction. (The
        // invoice-status revert of §9.10 step 4 is deferred: voiding restores
        // the balance and the credited-for-invoice reads self-heal through
        // the void_of_id filter, but the status COLUMN is only recomputed on
        // the payment path - see the handoff notes.)
        //
        // F-08: the receipt is found by its canonical link
        // (receipts.ledger_entry_id) FIRST. Converged payments - and every
        // core-written payment, which never carried receipt_no on the entry -
        // resolve here. The receipt_no fallback covers rows written before
        // convergence, which carry the number denormalized.
        {
          let receipt: Record<string, unknown> | null = null;
          const byEntryStmt = stmtFindLiveReceiptByEntry(tenantId, entryId);
          receipt = await oneRow(tx, byEntryStmt.sql, byEntryStmt.args);
          if (!receipt && entry.receiptNo) {
            const byNumberStmt = stmtFindLiveReceipt(tenantId, entry.receiptNo);
            receipt = await oneRow(tx, byNumberStmt.sql, byNumberStmt.args);
          }
          if (receipt) {
            const voidStmt = stmtVoidReceipt(tenantId, String(receipt.id), createdAt);
            await run(tx, voidStmt.sql, voidStmt.args);
            // Rule 7 / BR-SYN-01 - the EC-F-05 `voided_at` UPDATE above must
            // replicate too, or a reconnected replica shows a receipt as live
            // that the ledger already reversed.
            await recordOutbox(
              tx,
              tenantId,
              "receipts",
              String(receipt.id),
              "update",
              encodeOutboxPayload("receipts", "update", {
                id: receipt.id,
                tenant_id: tenantId,
                receipt_no: entry.receiptNo ?? null,
                voided_at: createdAt,
                updated_at: createdAt,
              }).payload,
            );
          }
        }

        await recordOutbox(
          tx,
          tenantId,
          "ledger_entries",
          voidRow.id,
          "create",
          encodeOutboxPayload("ledger_entries", "create", {
            void_of: entryId,
          }).payload,
        );
        // RFC-004 C1 — response bytes commit atomically with the void (see the
        // payment path). Business rejections above (404/409) abort WITHOUT
        // storing, so a retry with the same key re-executes.
        const payload = { ok: true, voidId: voidRow.id, newBalance };
        const env = okEnvelope(200, payload);
        await storeIdempotentResponse(tx, tenantId, idemRoute, idemKey, env.code, env.body);
        return payload;
      });
      // Cache invalidation follows COMMIT — see the payment path.
      invalidateTenant(tenantId);
      return ok(result);
    } catch (err) {
      // RFC-004 K2/K3 — concurrent-duplicate race (see the payment path).
      const replay = await replayIfDuplicate(db, tenantId, idemRoute, idemKey, err);
      if (replay) return replay;
      return mapLedgerRouteError(err);
    }
  }

  return null;
};
